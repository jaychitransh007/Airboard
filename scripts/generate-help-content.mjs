import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const helpRoot = path.join(repositoryRoot, "Docs", "help");
const outputFile = path.join(
  repositoryRoot,
  "apps",
  "web",
  "src",
  "generated",
  "helpContent.ts",
);
const checkOnly = process.argv.includes("--check");

const requiredFields = [
  "title",
  "description",
  "category",
  "categoryLabel",
  "order",
  "status",
  "audiences",
  "lastVerified",
  "sources",
];
const allowedStatuses = new Set([
  "shipped",
  "private-preview",
  "development-preview",
  "gated",
  "reference",
]);
const prohibitedClaims = [
  /available (?:in|from|on) the Chrome Web Store/i,
  /signed,? auto-updating installers (?:are )?available/i,
  /Zoom (?:is )?supported/i,
  /Microsoft Teams (?:is )?supported/i,
  /Airboard stores no transcript data/i,
];

if (!existsSync(helpRoot)) {
  fail(`Help source directory does not exist: ${relative(helpRoot)}`);
}

const sourceFiles = (await collectMarkdownFiles(helpRoot)).filter(
  (file) => path.basename(file).toLowerCase() !== "readme.md",
);
if (sourceFiles.length === 0) {
  fail(`No help articles found under ${relative(helpRoot)}`);
}

const sourceFileSet = new Set(sourceFiles.map((file) => path.normalize(file)));
const articles = [];
const errors = [];

for (const file of sourceFiles) {
  const source = await readFile(file, "utf8");
  const parsed = parseFrontmatter(source, file);
  if (!parsed) continue;
  const { metadata, body } = parsed;

  for (const field of requiredFields) {
    if (metadata[field] === undefined || metadata[field] === "") {
      errors.push(`${relative(file)}: missing required frontmatter field "${field}"`);
    }
  }

  if (!allowedStatuses.has(metadata.status)) {
    errors.push(
      `${relative(file)}: status must be one of ${[...allowedStatuses].join(", ")}`,
    );
  }
  if (!Array.isArray(metadata.audiences) || metadata.audiences.length === 0) {
    errors.push(`${relative(file)}: audiences must be a non-empty JSON array`);
  }
  if (!Array.isArray(metadata.sources) || metadata.sources.length === 0) {
    errors.push(`${relative(file)}: sources must be a non-empty JSON array`);
  }
  if (!Number.isFinite(metadata.order)) {
    errors.push(`${relative(file)}: order must be a number`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(metadata.lastVerified ?? ""))) {
    errors.push(`${relative(file)}: lastVerified must use YYYY-MM-DD`);
  }

  for (const sourcePath of Array.isArray(metadata.sources) ? metadata.sources : []) {
    if (typeof sourcePath !== "string" || !existsSync(path.join(repositoryRoot, sourcePath))) {
      errors.push(`${relative(file)}: source path does not exist: ${String(sourcePath)}`);
    }
  }
  for (const pattern of prohibitedClaims) {
    if (pattern.test(body)) {
      errors.push(`${relative(file)}: contains prohibited claim matching ${pattern}`);
    }
  }
  validateLinks(file, body, sourceFileSet, errors);

  const slug = articleSlug(file);
  const headings = extractHeadings(body);
  articles.push({
    slug,
    title: String(metadata.title ?? ""),
    description: String(metadata.description ?? ""),
    category: String(metadata.category ?? ""),
    categoryLabel: String(metadata.categoryLabel ?? ""),
    order: Number(metadata.order),
    status: String(metadata.status ?? ""),
    audiences: Array.isArray(metadata.audiences) ? metadata.audiences.map(String) : [],
    lastVerified: String(metadata.lastVerified ?? ""),
    sources: Array.isArray(metadata.sources) ? metadata.sources.map(String) : [],
    headings,
    body: body.trim(),
    searchText: markdownToText(`${metadata.title ?? ""}\n${metadata.description ?? ""}\n${body}`),
  });
}

const duplicateSlugs = duplicates(articles.map((article) => article.slug));
for (const slug of duplicateSlugs) errors.push(`Duplicate help slug: ${slug}`);

articles.sort(
  (left, right) =>
    left.category.localeCompare(right.category) ||
    left.order - right.order ||
    left.title.localeCompare(right.title),
);

if (errors.length > 0) {
  fail(errors.join("\n"));
}

const generated = `/* eslint-disable */
// Generated by scripts/generate-help-content.mjs. Do not edit directly.

export type HelpArticleStatus =
  | "shipped"
  | "private-preview"
  | "development-preview"
  | "gated"
  | "reference";

export type HelpHeading = {
  depth: 2 | 3;
  id: string;
  label: string;
};

export type HelpArticle = {
  slug: string;
  title: string;
  description: string;
  category: string;
  categoryLabel: string;
  order: number;
  status: HelpArticleStatus;
  audiences: string[];
  lastVerified: string;
  sources: string[];
  headings: HelpHeading[];
  body: string;
  searchText: string;
};

export const HELP_ARTICLES: readonly HelpArticle[] = ${JSON.stringify(articles, null, 2)};
`;

const current = existsSync(outputFile) ? await readFile(outputFile, "utf8") : "";
if (checkOnly) {
  if (current !== generated) {
    fail(
      `${relative(outputFile)} is out of date. Run "pnpm docs:build" and commit the result.`,
    );
  }
  console.log(`Help documentation check passed (${articles.length} articles).`);
} else {
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, generated, "utf8");
  console.log(`Generated ${relative(outputFile)} from ${articles.length} help articles.`);
}

async function collectMarkdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectMarkdownFiles(target)));
    if (entry.isFile() && entry.name.endsWith(".md")) files.push(target);
  }
  return files.sort();
}

function parseFrontmatter(source, file) {
  if (!source.startsWith("---\n")) {
    errors.push(`${relative(file)}: file must start with frontmatter`);
    return null;
  }
  const end = source.indexOf("\n---\n", 4);
  if (end < 0) {
    errors.push(`${relative(file)}: frontmatter is not closed`);
    return null;
  }
  const metadata = {};
  for (const [index, line] of source.slice(4, end).split("\n").entries()) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const separator = line.indexOf(":");
    if (separator < 1) {
      errors.push(`${relative(file)}:${index + 2}: invalid frontmatter line`);
      continue;
    }
    const key = line.slice(0, separator).trim();
    const raw = line.slice(separator + 1).trim();
    try {
      metadata[key] = parseFrontmatterValue(raw);
    } catch (error) {
      errors.push(`${relative(file)}:${index + 2}: ${error.message}`);
    }
  }
  return { metadata, body: source.slice(end + 5) };
}

function parseFrontmatterValue(raw) {
  if (raw.startsWith("[") || raw.startsWith("{") || raw.startsWith('"')) {
    return JSON.parse(raw);
  }
  if (/^-?\d+(?:\.\d+)?$/.test(raw)) return Number(raw);
  if (raw === "true") return true;
  if (raw === "false") return false;
  return raw;
}

function articleSlug(file) {
  return relativeToHelp(file)
    .replace(/\.md$/i, "")
    .split(path.sep)
    .map((part) => part.replace(/^\d+-/, ""))
    .join("/");
}

function extractHeadings(body) {
  const seen = new Map();
  return body
    .split("\n")
    .flatMap((line) => {
      const match = /^(#{2,3})\s+(.+?)\s*$/.exec(line);
      if (!match) return [];
      const label = markdownToText(match[2]);
      const base = slugify(label);
      const count = seen.get(base) ?? 0;
      seen.set(base, count + 1);
      return [
        {
          depth: match[1].length,
          id: count === 0 ? base : `${base}-${count + 1}`,
          label,
        },
      ];
    });
}

function validateLinks(file, body, knownFiles, targetErrors) {
  const links = body.matchAll(/\[[^\]]+\]\(([^)]+)\)/g);
  for (const match of links) {
    const rawTarget = match[1].trim().replace(/^<|>$/g, "");
    if (
      !rawTarget ||
      rawTarget.startsWith("#") ||
      rawTarget.startsWith("/") ||
      /^[a-z]+:/i.test(rawTarget)
    ) {
      continue;
    }
    const withoutAnchor = decodeURIComponent(rawTarget.split("#")[0]);
    const resolved = path.normalize(path.resolve(path.dirname(file), withoutAnchor));
    if (!knownFiles.has(resolved) && !existsSync(resolved)) {
      targetErrors.push(`${relative(file)}: broken relative link: ${rawTarget}`);
    }
  }
}

function markdownToText(value) {
  return String(value)
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/!\[[^\]]*\]\([^)]+\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/[*_>#|~-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

function duplicates(values) {
  const seen = new Set();
  const found = new Set();
  for (const value of values) {
    if (seen.has(value)) found.add(value);
    seen.add(value);
  }
  return [...found];
}

function relativeToHelp(file) {
  return path.relative(helpRoot, file);
}

function relative(file) {
  return path.relative(repositoryRoot, file) || ".";
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
